// البحث بالاسم يستخدم LIKE، و% و_ لهما معنى خاص داخله: % تطابق أي شي، و_
// تطابق أي حرف. الموظف اللي يكتب % بخانة البحث ما يقصد "كل شي" — بس هذا اللي
// كان يصير: الاستعلام يرجّع كل صفوف الجدول، وكل صف يمر على فك تشفير رقم
// الهاتف. يعني نقرة فضول وحدة تطلّع أرقام كل العملاء برد واحد.
//
// النسخة المزيّفة بالتستات تستخدم includes()، يعني نص حرفي بلا رموز خاصة —
// فالتهريب هذا يخلي السلوك الحقيقي يطابق اللي التستات تفحصه، مو العكس
export const LIKE_ESCAPE_CHAR = '\\'

export function escapeLikeWildcards(value: string): string {
  // الباكسلاش أول واحد عمدًا: لو هرّبنا % قبله نرجع نهرّب الباكسلاش اللي ضفناه
  return value.replace(/[\\%_]/g, (character) => `${LIKE_ESCAPE_CHAR}${character}`)
}
