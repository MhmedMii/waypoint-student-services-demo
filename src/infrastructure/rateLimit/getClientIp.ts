import type { NextRequest } from 'next/server'

// ياخذ أول قيمة من x-forwarded-for، وهي عادةً الطرف اللي يتحكم فيه المنادي —
// بس مو هنا. فيرسل يستبدل الهيدر كامل بالـ IP اللي جا منه اتصال TCP، وما
// يمرر أي IP خارجي، وهذا مكتوب بتوثيقه حرفياً كإجراء ضد انتحال الـ IP:
// https://vercel.com/docs/headers/request-headers
// يعني القيمة اللي نقراها هنا كتبها فيرسل مو المتصل، والقيمة وحدة مو سلسلة،
// فأخذ الأولى هو الصح. ولو أحد جرّب يزوّر الهيدر، حافة فيرسل ترميه قبل يوصل.
//
// الأمان هنا معتمد على إننا خلف حافة فيرسل، مو على الكود نفسه. نقطتان تكسرانه:
// ١. التشغيل الذاتي بالـ Dockerfile: npm start على المنفذ 3000 مباشرة بلا أي
//    بروكسي، فالهيدر يصير كلام المنادي — أو ما يجي أصلاً فنرجع 'unknown'
//    ويصير حد الـ IP مطفي تماماً.
// ٢. وضع CDN قدام فيرسل (كلاودفلير مثلاً): وقتها الهيدر يحمل IP البروكسي،
//    فكل العملاء ينحشرون بسلة وحدة ويتحظرون مع بعض دفعة وحدة.
// أي واحدة من هاتين تحتاج تغيير هنا — قبلها لا.
//
// 'unknown' معناها ما عرفنا المتصل، والمنادي المفروض ما يحظر عليها: سلة وحدة
// يتشاركها كل الناس، فحظرها يحظر الجميع سوا.
//
// قرار ثقة واحد، تنفيذ واحد. كانت فيه نسخة ثانية خاصة بتسجيل الدخول: بلا تست،
// وبلا هالملاحظة، وتعامل الهيدر لو جا مصفوفة كأنه مجهول — فيطفي حد الـ IP على
// تسجيل الدخول بالذات. الحين الطرفان يمرّون من هنا.
//
// القيمة الخام: نص من NextRequest، أو من كائن الهيدرز العادي اللي يمرّره
// NextAuth — وهناك ممكن تجي مصفوفة لو تكرر الهيدر. نأخذ السطر الأول ثم أول
// عنوان فيه. ولو طلع فاضي بعد القص ("," أو مسافات) فهو مجهول، مو "" — النص
// الفاضي كان يعدّي فحص 'unknown' ويصير مفتاح حظر يتشاركه كل من يرسله
export function clientIpFromForwardedFor(value: unknown): string {
  const header = Array.isArray(value) ? value[0] : value
  if (typeof header !== 'string') return 'unknown'
  const first = header.split(',')[0].trim()
  return first === '' ? 'unknown' : first
}

export function getClientIp(request: NextRequest): string {
  return clientIpFromForwardedFor(request.headers.get('x-forwarded-for'))
}
